"""Properties of bin/commit-gate, checked with Hegel (https://hegel.dev).

  python3 properties/commit_gate_hook_agreement.py [PATH-TO-COMMIT-GATE]   # needs: pip install hegeltest==0.5.1

commit-gate's attribution check runs in two places against the same
`attribution_re`: the pre-commit hook, which greps each added diff line, and
the commit-msg hook, which greps the message body. For the same line of text,
both must reach the same verdict -- whatever tool name, trailer, casing,
leading symbol or surrounding prose the line has. A regex change applied to
only one of the two code paths, or an extraction bug in the pre-commit awk
pipeline, would make them disagree while each still "works" on its own.

Proposed by Property Scout; held on a48cbf1 (25 cases).
"""
import os
import subprocess
import sys
import tempfile

import hegel
from hegel import generators as gs

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The script under test: the first argument, else $COMMIT_GATE, else this checkout's.
COMMIT_GATE = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else
                              os.environ.get("COMMIT_GATE", os.path.join(ROOT, "bin", "commit-gate")))

TOOLS = ["claude", "codex", "cursor", "copilot", "gemini", "chatgpt", "windsurf", "tabnine", "robot"]
TRAILERS = ["Co-Authored-By", "Claude-Session"]
PREFIXES = ["", "> ", "🤖 ", "- ", "* "]


def git(cwd, *args):
    subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", *args], cwd=cwd,
                   check=True, capture_output=True)


def cased(tc, s):
    flips = tc.draw(gs.lists(gs.booleans(), min_size=len(s), max_size=len(s)))
    return "".join(c.upper() if up else c.lower() for c, up in zip(s, flips))


def pre_commit_blocks(line):
    """Whether commit-gate's pre-commit hook refuses a commit whose only added line is `line`."""
    with tempfile.TemporaryDirectory() as d:
        git(d, "init", "-q", "-b", "main")
        git(d, "config", "commitgate.attribution", "true")
        with open(os.path.join(d, "NOTES.md"), "w") as f:
            f.write(line + "\n")
        git(d, "add", "-A")
        out = subprocess.run(["bash", COMMIT_GATE, "run", "pre-commit"], cwd=d, capture_output=True, text=True)
        return out.returncode != 0


def commit_msg_blocks(line):
    """Whether commit-gate's commit-msg hook refuses a message whose body is just `line`."""
    with tempfile.TemporaryDirectory() as d:
        git(d, "init", "-q", "-b", "main")
        git(d, "config", "commitgate.attribution", "true")
        git(d, "config", "commitgate.conventional", "false")
        path = os.path.join(d, "MSG")
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"feat: add shout\n\n{line}\n")
        out = subprocess.run(["bash", COMMIT_GATE, "run", "commit-msg", path], cwd=d,
                             capture_output=True, text=True)
        return out.returncode != 0


@hegel.test(test_cases=25)
def test_pre_commit_and_commit_msg_agree(tc):
    kind = tc.draw(gs.sampled_from(["footer", "trailer", "prose"]))
    if kind == "footer":
        prefix = tc.draw(gs.sampled_from(PREFIXES))
        word = tc.draw(gs.sampled_from(["with", "by"]))
        bracket = "[" if tc.draw(gs.booleans()) else ""
        tool = cased(tc, tc.draw(gs.sampled_from(TOOLS)))
        line = f"{prefix}{cased(tc, 'generated')} {cased(tc, word)} {bracket}{tool}"
    elif kind == "trailer":
        name = cased(tc, tc.draw(gs.sampled_from(TRAILERS)))
        line = f"{name}: x"
    else:
        lead = tc.draw(gs.sampled_from(["The gate refuses a", "Do not add a", "See the"]))
        term = tc.draw(gs.sampled_from(["Generated by codex footer", "Generated with claude line",
                                        "Co-Authored-By: trailer", "Claude-Session: line"]))
        line = f"{lead} {cased(tc, term)}."

    pre = pre_commit_blocks(line)
    msg = commit_msg_blocks(line)
    assert pre == msg, f"hooks disagree on {line!r}: pre-commit={pre}, commit-msg={msg}"


if __name__ == "__main__":
    test_pre_commit_and_commit_msg_agree()
    print("commit_gate_hook_agreement: properties held")
