"""Properties of bin/commit-gate's attribution check, checked with Hegel (https://hegel.dev).

  python3 properties/commit_gate.py [PATH-TO-COMMIT-GATE]   # needs: pip install hegeltest==0.5.1

A commit message whose body has an AI attribution line is refused, whatever the
letter case: a Co-Authored-By or Claude-Session trailer, or a "Generated with
<tool>" or "Generated by <tool>" footer, with or without a leading emoji or
bullet and a [ before the tool's name; the same words inside a sentence are
not. Each case writes the message to a file
in a scratch repository and runs the commit-msg hook's check on it.

Red: on blind probe #45's bin/commit-gate (276fb44, "generated (with|by)"
narrowed to "generated[- ]with") this fails, and Hegel shrinks it to a single
"generated by" footer. Property Scout proposed the "by" half on that PR.
"""
import os
import subprocess
import sys
import tempfile

import hegel
from hegel import generators as gs

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The script under test: the first argument, else $COMMIT_GATE, else this checkout's.
GATE = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else
                       os.environ.get("COMMIT_GATE", os.path.join(ROOT, "bin", "commit-gate")))
TOOLS = ["claude", "codex", "cursor", "copilot", "gemini", "chatgpt"]
TRAILERS = ["Co-Authored-By", "Claude-Session"]
PREFIXES = ["", "🤖 ", "- ", "* "]


def git(cwd, *args):
    subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", *args], cwd=cwd,
                   check=True, capture_output=True)


def cased(tc, s):
    flips = tc.draw(gs.lists(gs.booleans(), min_size=len(s), max_size=len(s)))
    return "".join(c.upper() if up else c.lower() for c, up in zip(s, flips))


def refused(message):
    """Whether commit-gate's commit-msg check refuses `message`."""
    with tempfile.TemporaryDirectory() as d:
        git(d, "init", "-q", "-b", "main")
        git(d, "config", "commitgate.attribution", "true")
        git(d, "config", "commitgate.conventional", "false")
        path = os.path.join(d, "MSG")
        with open(path, "w", encoding="utf-8") as f:
            f.write(message)
        out = subprocess.run(["bash", GATE, "run", "commit-msg", path], cwd=d,
                             capture_output=True, text=True)
        if out.returncode == 0:
            return False
        # Only the attribution refusal counts: a wrong path or a usage error must fail the
        # property, not make every case look refused.
        assert out.returncode == 1 and "AI attribution" in out.stderr, out.stderr
        return True


@hegel.test(test_cases=25)
def test_generated_footers_are_refused(tc):
    prefix = tc.draw(gs.sampled_from(PREFIXES))
    word = tc.draw(gs.sampled_from(["with", "by"]))
    bracket = "[" if tc.draw(gs.booleans()) else ""
    tool = cased(tc, tc.draw(gs.sampled_from(TOOLS)))
    line = f"{prefix}{cased(tc, 'generated')} {cased(tc, word)} {bracket}{tool}"
    assert refused(f"feat: add shout\n\n{line}\n"), f"not refused: {line!r}"


@hegel.test(test_cases=25)
def test_trailers_are_refused(tc):
    name = cased(tc, tc.draw(gs.sampled_from(TRAILERS)))
    line = f"{name}: x"
    assert refused(f"feat: add shout\n\n{line}\n"), f"not refused: {line!r}"


@hegel.test(test_cases=25)
def test_a_message_without_attribution_is_accepted(tc):
    # The same footers and trailers mentioned inside a sentence are prose, not attribution,
    # so a gate that refused every message fails here.
    lead = tc.draw(gs.sampled_from(["The gate refuses a", "Do not add a", "See the"]))
    term = tc.draw(gs.sampled_from(["Generated by codex footer", "Generated with claude line",
                                    "Co-Authored-By: trailer", "Claude-Session: line"]))
    line = f"{lead} {cased(tc, term)}."
    assert not refused(f"docs: explain the gate\n\n{line}\n"), f"wrongly refused: {line!r}"


if __name__ == "__main__":
    test_generated_footers_are_refused()
    test_trailers_are_refused()
    test_a_message_without_attribution_is_accepted()
    print("commit_gate: properties held")
