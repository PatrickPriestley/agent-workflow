#!/usr/bin/env bash
# Tests for bin/probe-score: one verdict per review loop for a probe, from its answer key and
# the evidence on its pull request. #37 (loud) and #45 (silent) are the known answers.
#   bash bin/probe-score.test.sh
set -u
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PS=(python3 -I "$here/probe-score"); D="$here/testdata/probes"
pass=0; fail=0; CURRENT=""
it() { CURRENT="$1"; }
ok()  { pass=$((pass+1)); printf '  ok   %s\n' "$CURRENT"; }
bad() { fail=$((fail+1)); printf '  FAIL %s\n       %s\n' "$CURRENT" "$1"; }
assert_eq() { [ "$1" = "$2" ] && ok || bad "expected [$1] got [$2]"; }
verdicts() {  # JSONL on stdin -> "loop=verdict" lines, sorted
  python3 -c 'import json,sys; print("\n".join(sorted(r["loop"] + "=" + r["verdict"] for r in map(json.loads, sys.stdin))))'
}
T="$(mktemp -d "${TMPDIR:-/tmp}/probe-score.XXXXXX")"; trap 'rm -rf "$T"' EXIT

it "#37, the loud probe: tests, Open Code Review, CI diagnosis, CI fix and Property Scout caught it"
got="$("${PS[@]}" "$D/37/key.json" "$D/37/evidence.json" | verdicts)"
assert_eq "ci-diagnose=caught
ci-fix=caught
mutation=no data
ocr=caught
properties=no data
property-scout=caught
tests=caught
verify=not run" "$got"

it "#45, the silent probe: only Property Scout caught it; Verify never tested the false claim"
got="$("${PS[@]}" "$D/45/key.json" "$D/45/evidence.json" | verdicts)"
assert_eq "ci-diagnose=not run
ci-fix=not run
mutation=missed
ocr=not run
properties=missed
property-scout=caught
tests=missed
verify=missed" "$got"

it "every row names the probe, the bug kind, loud or silent, and quotes its evidence"
"${PS[@]}" "$D/37/key.json" "$D/37/evidence.json" | python3 -c '
import json,sys
rows=[json.loads(l) for l in sys.stdin]
assert all(r["probe"]=="probe-37" and r["kind"]=="dropped-alternative" and r["loud"] is True for r in rows), rows
ocr=[r for r in rows if r["loop"]=="ocr"][0]
assert "bin/pr-size:61" in ocr["evidence"], ocr' && ok || bad "row fields or OCR evidence wrong"

# Variations on #45's evidence.
variant() {  # NAME PYTHON-EXPRESSION-ON-e -> $T/NAME.json
  python3 -c 'import json,sys; e=json.load(open(sys.argv[1])); exec(sys.argv[2]); json.dump(e,open(sys.argv[3],"w"))' \
    "$D/45/evidence.json" "$2" "$T/$1.json"
}
one() {  # EVIDENCE LOOP -> verdict
  "${PS[@]}" "$D/45/key.json" "$1" | python3 -c 'import json,sys; print([r["verdict"] for r in map(json.loads,sys.stdin) if r["loop"]==sys.argv[1]][0])' "$2"
}
it "Open Code Review: a comment within 3 lines of the planted lines is caught; on another file it is missed"
variant near 'e["review_comments"]=[{"path":"bin/commit-gate","line":29,"original_line":29,"body":"x"}]; e["comments"].append({"body":"<!-- ocr-summary -->"})'
assert_eq caught "$(one "$T/near.json" ocr)"
variant far 'e["review_comments"]=[{"path":"bin/commit-gate","line":40,"original_line":40,"body":"x"}]; e["comments"].append({"body":"<!-- ocr-summary -->"})'
assert_eq missed "$(one "$T/far.json" ocr)"
variant other 'e["review_comments"]=[{"path":"README.md","line":22,"original_line":22,"body":"x"}]; e["comments"].append({"body":"<!-- ocr-summary -->"})'
assert_eq missed "$(one "$T/other.json" ocr)"
it "Verify: a differs verdict on the false claim is caught"
variant vcaught 'e["comments"][0]["body"]="**Summary**: matches 0, differs 1, not checked 1.\n\n### Differs\n\n- \"Existing patterns are unchanged\": Generated by lines are now accepted.\n<!-- gh-aw-workflow-call-id: PatrickPriestley/agent-workflow/verify -->"'
assert_eq caught "$(one "$T/vcaught.json" verify)"
it "Verify: naming the false claim without a differs verdict is still missed"
variant vnamed 'e["comments"][0]["body"]="**Summary**: matches 0, differs 0, not checked 1.\n\n### Not checked\n\n- \"Existing patterns are unchanged\": could not run the tests.\n<!-- gh-aw-workflow-call-id: PatrickPriestley/agent-workflow/verify -->"'
assert_eq missed "$(one "$T/vnamed.json" verify)"
it "CI diagnosis: naming the bug's term without the file is left to the judge"
python3 -c 'import json,sys; e=json.load(open(sys.argv[1])); e["comments"][1]["body"]="yarn.lock changed somewhere.\n<!-- gh-aw-workflow-call-id: PatrickPriestley/agent-workflow/ci-diagnose -->"; json.dump(e,open(sys.argv[2],"w"))' "$D/37/evidence.json" "$T/dterm.json"
assert_eq judge "$("${PS[@]}" "$D/37/key.json" "$T/dterm.json" | python3 -c 'import json,sys; print([r["verdict"] for r in map(json.loads,sys.stdin) if r["loop"]=="ci-diagnose"][0])')"
it "Property Scout: no failures is missed; a failure about something else is left to the judge"
variant snone 'e["comments"][1]["body"]="| p | held (25 cases) |\n\nNo failures.\n<!-- gh-aw-workflow-call-id: PatrickPriestley/agent-workflow/property-scout -->"'
assert_eq missed "$(one "$T/snone.json" property-scout)"
variant sother 'e["comments"][1]["body"]="| p | **failed on head** |\n\nshrunk counterexample: x=0\n<!-- gh-aw-workflow-call-id: PatrickPriestley/agent-workflow/property-scout -->"'
assert_eq judge "$(one "$T/sother.json" property-scout)"
it "a loop's agent comment counts only with its own workflow marker"
variant nomark 'e["comments"][1]["body"]=e["comments"][1]["body"].replace("property-scout -->","other -->")'
assert_eq "not run" "$(one "$T/nomark.json" property-scout)"
it "an agent loop whose run failed with no comment is failed, not 'not run'; a skipped one is not run"
# #68: Property Scout's threat detection produced no result, so its run failed and posted nothing.
python3 -c '
import json, sys
e = json.load(open(sys.argv[1]))
e["comments"] = [c for c in e["comments"] if "agent-workflow/property-scout" not in c["body"]]
e["checks"]["Property Scout"] = sys.argv[3]
json.dump(e, open(sys.argv[2], "w"))' "$D/45/evidence.json" "$T/sfail.json" failure
assert_eq failed "$("${PS[@]}" "$D/45/key.json" "$T/sfail.json" | python3 -c 'import json,sys; print([r["verdict"] for r in map(json.loads,sys.stdin) if r["loop"]=="property-scout"][0])')"
python3 -c '
import json, sys
e = json.load(open(sys.argv[1])); e["checks"]["Property Scout"] = "skipped"; json.dump(e, open(sys.argv[2], "w"))' "$T/sfail.json" "$T/sskip.json"
assert_eq "not run" "$("${PS[@]}" "$D/45/key.json" "$T/sskip.json" | python3 -c 'import json,sys; print([r["verdict"] for r in map(json.loads,sys.stdin) if r["loop"]=="property-scout"][0])')"
it "a failed loop is left out of the loops that ran, and named in the score line"
md="$("${PS[@]}" --markdown "$D/45/key.json" "$T/sfail.json")"
ran_before="$("${PS[@]}" --markdown "$D/45/key.json" "$D/45/evidence.json" | sed -n 's/.*of the \([0-9]*\) loops that ran.*/\1/p')"
ran_after="$(printf '%s\n' "$md" | sed -n 's/.*of the \([0-9]*\) loops that ran.*/\1/p')"
assert_eq "$((ran_before - 1))" "$ran_after"
printf '%s\n' "$md" | grep -qF 'Failed to run: property-scout.' && ok || bad "score line: $(printf '%s\n' "$md" | sed -n 3p)"
it "a missing check is no data, not missed"
variant nochk 'del e["checks"]["properties"]'
assert_eq "no data" "$(one "$T/nochk.json" properties)"
it "--markdown prints one table row per loop, with the score line, and no raw pipe or newline from a field"
md="$("${PS[@]}" --markdown "$D/37/key.json" "$D/37/evidence.json")"
printf '%s\n' "$md" | grep -qF 'Caught by 5 of the 5 loops that ran.' && ok || bad "score line: $md"
assert_eq 8 "$(printf '%s\n' "$md" | grep -c '^| [a-z-]* | ')"
python3 -c 'import json,sys; k=json.load(open(sys.argv[1])); k["kind"]="a|b\nc"; json.dump(k,open(sys.argv[2],"w"))' "$D/37/key.json" "$T/pipekey.json"
"${PS[@]}" --markdown "$T/pipekey.json" "$D/37/evidence.json" | head -1 | grep -qF 'a\|b c' && ok || bad "kind not escaped"
it "a missing file or a key without its fields is a usage error"
"${PS[@]}" "$D/45/key.json" "$T/missing.json" >/dev/null 2>&1; assert_eq 2 "$?"
printf '{"id":"x"}' > "$T/badkey.json"
"${PS[@]}" "$T/badkey.json" "$D/45/evidence.json" >/dev/null 2>&1; assert_eq 2 "$?"

echo; echo "passed=$pass failed=$fail"
[ "$fail" -eq 0 ]
