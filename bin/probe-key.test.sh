#!/usr/bin/env bash
# Tests for bin/probe-key: seal and open a probe's answer key, and the hash a probe PR carries.
#   bash bin/probe-key.test.sh
set -u
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
K="$here/probe-key"
pass=0; fail=0; CURRENT=""
it() { CURRENT="$1"; }
ok()  { pass=$((pass+1)); printf '  ok   %s\n' "$CURRENT"; }
bad() { fail=$((fail+1)); printf '  FAIL %s\n       %s\n' "$CURRENT" "$1"; }
assert_eq() { [ "$1" = "$2" ] && ok || bad "expected [$1] got [$2]"; }

T="$(mktemp -d "${TMPDIR:-/tmp}/probe-key.XXXXXX")"; trap 'rm -rf "$T"' EXIT
printf '{"id":"probe-1","file":"bin/x","counterexample":"generated by codex"}\n' > "$T/key.json"

it "seal then open gives back the key exactly"
PROBE_KEY=s3cret "$K" seal "$T/key.json" > "$T/key.sealed"; assert_eq 0 "$?"
PROBE_KEY=s3cret "$K" open "$T/key.sealed" > "$T/out.json"; assert_eq 0 "$?"
cmp -s "$T/key.json" "$T/out.json" && ok || bad "round trip changed the key"
it "a key without a final newline comes back byte for byte"
printf '{"id":"probe-2"}' > "$T/bare.json"
PROBE_KEY=s3cret "$K" seal "$T/bare.json" > "$T/bare.sealed"
PROBE_KEY=s3cret "$K" open "$T/bare.sealed" | cmp -s - "$T/bare.json" && ok || bad "bytes changed"
it "the sealed key does not contain the plaintext"
grep -q 'generated by codex' "$T/key.sealed" && bad "plaintext visible" || ok
it "opening with the wrong secret fails and prints nothing of the key"
out="$(PROBE_KEY=wrong "$K" open "$T/key.sealed" 2>/dev/null)"; assert_eq 1 "$?"
printf '%s' "$out" | grep -q 'codex' && bad "printed key material" || ok
it "seal and open need PROBE_KEY; with none they are usage errors"
(unset PROBE_KEY; "$K" seal "$T/key.json" >/dev/null 2>&1); assert_eq 2 "$?"
(unset PROBE_KEY; "$K" open "$T/key.sealed" >/dev/null 2>&1); assert_eq 2 "$?"
it "hash prints 64 hex digits, the same for the same key, different after any change"
h1="$("$K" hash "$T/key.json")"; h2="$("$K" hash "$T/key.json")"
printf '%s' "$h1" | grep -qE '^[0-9a-f]{64}$' && ok || bad "hash: [$h1]"
assert_eq "$h1" "$h2"
printf '{"id":"probe-1","file":"bin/y","counterexample":"generated by codex"}\n' > "$T/other.json"
[ "$("$K" hash "$T/other.json")" != "$h1" ] && ok || bad "a changed key has the same hash"
it "check: 0 when the sealed key opens to the hashed key, 1 when it does not"
PROBE_KEY=s3cret "$K" check "$T/key.sealed" "$h1" >/dev/null 2>&1; assert_eq 0 "$?"
PROBE_KEY=s3cret "$K" check "$T/key.sealed" "$("$K" hash "$T/other.json")" >/dev/null 2>&1; assert_eq 1 "$?"
PROBE_KEY=s3cret "$K" seal "$T/other.json" > "$T/other.sealed"
PROBE_KEY=s3cret "$K" check "$T/other.sealed" "$h1" >/dev/null 2>&1; assert_eq 1 "$?"
it "an unknown command, or a missing file, is a usage error"
"$K" nope >/dev/null 2>&1; assert_eq 2 "$?"
"$K" hash "$T/missing.json" >/dev/null 2>&1; assert_eq 2 "$?"

echo; echo "passed=$pass failed=$fail"
[ "$fail" -eq 0 ]
